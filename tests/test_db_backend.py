"""数据后端适配层单元测试：方言转译 + SQLite 零回归 + 连接接口契约。"""
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core import db_backend as be  # noqa: E402


class TestSqlTranslation(unittest.TestCase):

    def test_placeholder_sqlite_untouched(self):
        sql = "SELECT * FROM users WHERE id=? AND name=?"
        out, ret, _ = be.translate_sql(sql, "sqlite")
        self.assertEqual(out, sql)
        self.assertFalse(ret)

    def test_placeholder_to_pyformat(self):
        sql = "SELECT * FROM users WHERE id=? AND name=?"
        out, _, _ = be.translate_sql(sql, "postgresql")
        self.assertEqual(out, "SELECT * FROM users WHERE id=%s AND name=%s")

    def test_question_mark_inside_literal_untouched(self):
        sql = "SELECT * FROM t WHERE note='what?' AND id=?"
        out, _, _ = be.translate_sql(sql, "mysql")
        self.assertEqual(out, "SELECT * FROM t WHERE note='what?' AND id=%s")

    def test_insert_returning_id_for_postgres(self):
        sql = "INSERT INTO users(username) VALUES(?)"
        out, ret, _ = be.translate_sql(sql, "postgresql")
        self.assertIn("RETURNING id", out)
        self.assertTrue(ret)

    def test_update_does_not_get_returning(self):
        sql = "UPDATE users SET role=? WHERE id=?"
        out, ret, _ = be.translate_sql(sql, "postgresql")
        self.assertNotIn("RETURNING", out)
        self.assertFalse(ret)

    def test_insert_or_replace_mysql(self):
        sql = ("INSERT OR REPLACE INTO project_members(project_id,user_id,role,created_at) "
               "VALUES(?,?,'owner',?)")
        out, _, _ = be.translate_sql(sql, "mysql")
        self.assertTrue(out.upper().startswith("REPLACE INTO PROJECT_MEMBERS"))
        self.assertIn("VALUES(%s,%s,'owner',%s)", out)
        self.assertNotIn(" S(", out)

    def test_insert_or_replace_postgres_upsert(self):
        sql = ("INSERT OR REPLACE INTO project_members(project_id,user_id,role,created_at) "
               "VALUES(?,?,'owner',?)")
        out, _, _ = be.translate_sql(sql, "postgresql")
        self.assertIn("ON CONFLICT(project_id,user_id) DO UPDATE SET", out)
        self.assertIn("EXCLUDED.role", out)
        self.assertIn("VALUES(%s,%s,'owner',%s)", out)
        self.assertNotIn("OR REPLACE", out.upper())

    def test_concat_mysql(self):
        sql = "(',' || COALESCE(e.tags,'') || ',') LIKE ?"
        out, _, _ = be.translate_sql(sql, "mysql")
        self.assertTrue(out.startswith("CONCAT("))
        self.assertIn("COALESCE(e.tags,'')", out)
        self.assertNotIn("||", out)

    def test_concat_postgres_untouched(self):
        sql = "(',' || COALESCE(e.tags,'') || ',') LIKE ?"
        out, _, _ = be.translate_sql(sql, "postgresql")
        self.assertIn("||", out)

    def test_pragma_ignored_by_connection(self):
        # SQLite 专有 PRAGMA 不应进入外部库；通过 translate 层之外的连接行为验证
        self.assertTrue(be._PRAGMA_IGNORE_RE.match("PRAGMA journal_mode=WAL"))
        self.assertTrue(be._PRAGMA_IGNORE_RE.match("PRAGMA busy_timeout=15000"))
        self.assertFalse(be._PRAGMA_IGNORE_RE.match("SELECT 1"))

    def test_table_info_pragma_recognized(self):
        m = be._PRAGMA_TABLE_INFO_RE.match("PRAGMA table_info(experiments)")
        self.assertIsNotNone(m)
        self.assertEqual(m.group(1), "experiments")


class TestDdlTranslation(unittest.TestCase):

    def test_ddl_sqlite_passthrough(self):
        self.assertEqual(be.translate_ddl("CREATE TABLE x(id INTEGER);", "sqlite"),
                         ["CREATE TABLE x(id INTEGER);"])

    def test_ddl_postgres_identity_and_double(self):
        script = "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, ts REAL);"
        stmts = be.translate_ddl(script, "postgresql")
        self.assertEqual(len(stmts), 1)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", stmts[0])
        self.assertIn("DOUBLE PRECISION", stmts[0])
        self.assertNotIn("AUTOINCREMENT", stmts[0])

    def test_ddl_mysql_auto_increment_and_no_if_not_exists(self):
        script = ("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, ts REAL);"
                  "CREATE INDEX IF NOT EXISTS idx_t ON t(id);")
        stmts = be.translate_ddl(script, "mysql")
        self.assertEqual(len(stmts), 2)
        self.assertIn("AUTO_INCREMENT", stmts[0])
        self.assertIn("DOUBLE", stmts[0])
        self.assertNotIn("IF NOT EXISTS", stmts[1])

    def test_ddl_strips_comments_and_splits(self):
        script = "-- 注释\nCREATE TABLE a(id INTEGER);\n-- 另一条\nCREATE TABLE b(id INTEGER);"
        self.assertEqual(len(be.translate_ddl(script, "mysql")), 2)


class TestBackendConfig(unittest.TestCase):

    def setUp(self):
        be.reset_backend_config()

    def test_normalize_backend(self):
        self.assertEqual(be._normalize_backend(""), "sqlite")
        self.assertEqual(be._normalize_backend("sqlite"), "sqlite")
        self.assertEqual(be._normalize_backend("postgresql"), "postgresql")
        self.assertEqual(be._normalize_backend("pg"), "postgresql")
        self.assertEqual(be._normalize_backend("mysql"), "mysql")
        with self.assertRaises(be.StorageError):
            be._normalize_backend("oracle")

    def test_default_is_sqlite(self):
        # 未改动 data/config.json 时（storage 缺省），必须回退到 sqlite
        st = be.backend_config()
        self.assertEqual(st["backend"], "sqlite")


if __name__ == "__main__":
    unittest.main()
